-- =========================================================
-- TRIGGERS: enforce "never sell more than you have" in the DB,
-- independent of the PHP checks (created after the seed rows so
-- the seed data doesn't touch stock, same as the MySQL version).
--
-- 1. check_stock  (BEFORE INSERT) rejects the row with SQLSTATE
--    45000 when stock is too low. FOR UPDATE locks the product
--    row so concurrent orders can't both pass the check.
-- 2. decrement_stock (AFTER INSERT) deducts stock and bumps
--    sold_count.
-- checkout.php maps SQLSTATE 45000 to a friendly message.
-- =========================================================
CREATE FUNCTION fn_orderdetails_check_stock() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  available INTEGER;
BEGIN
  IF NEW.product_id IS NOT NULL THEN
    SELECT stock INTO available FROM products WHERE product_id = NEW.product_id FOR UPDATE;
    IF available IS NOT NULL AND available < NEW.quantity THEN
      RAISE EXCEPTION 'Insufficient stock for the requested product.' USING ERRCODE = '45000';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE FUNCTION fn_orderdetails_decrement_stock() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.product_id IS NOT NULL THEN
    UPDATE products
       SET stock = stock - NEW.quantity,
           sold_count = sold_count + NEW.quantity
     WHERE product_id = NEW.product_id;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_orderdetails_check_stock
  BEFORE INSERT ON orderdetails
  FOR EACH ROW EXECUTE FUNCTION fn_orderdetails_check_stock();

CREATE TRIGGER trg_orderdetails_decrement_stock
  AFTER INSERT ON orderdetails
  FOR EACH ROW EXECUTE FUNCTION fn_orderdetails_decrement_stock();

-- =========================================================
-- Supabase safety: Supabase exposes every table in the public
-- schema through its REST API using a public "anon" key. With
-- RLS off, anyone holding that key could read customers
-- (including password hashes). Enabling RLS with no policies
-- blocks the API; the PHP app connects as the postgres role,
-- which bypasses RLS, so the site is unaffected. Harmless on
-- plain PostgreSQL.
-- =========================================================
ALTER TABLE categories   ENABLE ROW LEVEL SECURITY;
ALTER TABLE products     ENABLE ROW LEVEL SECURITY;
ALTER TABLE customers    ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders       ENABLE ROW LEVEL SECURITY;
ALTER TABLE orderdetails ENABLE ROW LEVEL SECURITY;

