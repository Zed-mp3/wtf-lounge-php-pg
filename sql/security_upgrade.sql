-- ---------------------------------------------------------
-- Login throttling (used by includes/auth.php). Stores one row per
-- failed login so lockouts survive a cleared session cookie.
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS login_attempts (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  throttle_key VARCHAR(80) NOT NULL,
  attempted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_login_attempts_key_time ON login_attempts (throttle_key, attempted_at);
ALTER TABLE login_attempts ENABLE ROW LEVEL SECURITY;

-- Tighten what the public Supabase "anon"/"authenticated" API roles can do.
-- (No-ops on plain PostgreSQL where those roles don't exist.)
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;
  END IF;
END $$;

COMMIT;
