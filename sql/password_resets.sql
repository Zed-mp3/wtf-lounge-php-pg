-- Forgot-password tables. Safe to run more than once (Supabase SQL editor).

-- Admin-issued / code-verified one-time reset links (used by includes/password_reset.php)
CREATE TABLE IF NOT EXISTS password_resets (
  reset_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id  INTEGER NOT NULL REFERENCES customers (customer_id) ON DELETE CASCADE,
  status       VARCHAR(20) NOT NULL DEFAULT 'requested'
               CHECK (status IN ('requested', 'link_issued', 'used', 'dismissed')),
  token_hash   VARCHAR(64),
  requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  issued_at    TIMESTAMPTZ,
  expires_at   TIMESTAMPTZ,
  used_at      TIMESTAMPTZ
);

-- One open row per customer (the ON CONFLICT clauses in the PHP code rely on this index).
CREATE UNIQUE INDEX IF NOT EXISTS password_resets_one_open_per_customer
  ON password_resets (customer_id) WHERE status IN ('requested', 'link_issued');

CREATE INDEX IF NOT EXISTS password_resets_token_hash_idx
  ON password_resets (token_hash) WHERE token_hash IS NOT NULL;

-- SMS verification codes: one live code per customer. Only a hash of the code is stored.
CREATE TABLE IF NOT EXISTS password_reset_codes (
  customer_id       INTEGER PRIMARY KEY REFERENCES customers (customer_id) ON DELETE CASCADE,
  code_hash         VARCHAR(255) NOT NULL,
  expires_at        TIMESTAMPTZ NOT NULL,
  attempts          INTEGER NOT NULL DEFAULT 0,
  sent_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  send_count        INTEGER NOT NULL DEFAULT 1,
  window_started_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Supabase exposes public tables through its REST API. Turn on RLS with no policies so only
-- your server (the postgres role used by config/db.php) can read these tables.
ALTER TABLE password_resets      ENABLE ROW LEVEL SECURITY;
ALTER TABLE password_reset_codes ENABLE ROW LEVEL SECURITY;
